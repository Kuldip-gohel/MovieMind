"""Build MovieMind's sparse content-based recommendation model.

The input movies_processed.pkl is the processed dataframe generated by the
original MovieMind notebook. Its tags already include overview, genres,
keywords, top cast, director, lowercasing and Porter stemming.
"""
from pathlib import Path
import json
import pickle
from sklearn.feature_extraction.text import CountVectorizer
from scipy.sparse import save_npz

ROOT = Path(__file__).resolve().parents[1]
DATA_DIR = ROOT / "data"
MODEL_DIR = ROOT / "model"
SOURCE = DATA_DIR / "movies_processed.pkl"


def main():
    MODEL_DIR.mkdir(parents=True, exist_ok=True)
    if not SOURCE.exists():
        raise FileNotFoundError(
            f"Missing {SOURCE}. Place your processed movies.pkl file in backend/data/ "
            "and name it movies_processed.pkl."
        )

    with SOURCE.open("rb") as file:
        movies = pickle.load(file)

    required = {"movie_id", "title", "tags"}
    missing = required.difference(movies.columns)
    if missing:
        raise ValueError(f"Processed movie dataframe is missing columns: {sorted(missing)}")

    movies = movies.dropna(subset=["title", "tags"]).reset_index(drop=True)
    movies["title"] = movies["title"].astype(str)
    movies["tags"] = movies["tags"].astype(str)

    # Keep the original notebook's CountVectorizer configuration.
    vectorizer = CountVectorizer(max_features=5000, stop_words="english")
    vectors = vectorizer.fit_transform(movies["tags"])

    # Save vectors sparsely. Do not create the large dense similarity.pkl matrix.
    save_npz(MODEL_DIR / "movie_vectors.npz", vectors, compressed=True)
    with (MODEL_DIR / "vectorizer_vocab.json").open("w", encoding="utf-8") as file:
        json.dump({token: int(index) for token, index in vectorizer.vocabulary_.items()}, file)
    movies.to_pickle(MODEL_DIR / "movies_processed.pkl")

    print(f"Built model for {len(movies):,} movies.")
    print(f"Sparse matrix shape: {vectors.shape}; non-zero values: {vectors.nnz:,}")
    print(f"Artifacts saved in: {MODEL_DIR}")


if __name__ == "__main__":
    main()
